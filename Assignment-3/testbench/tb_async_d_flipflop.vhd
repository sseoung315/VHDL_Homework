library ieee;
use ieee.std_logic_1164.all;
use std.env.all;
entity tb_async_d_flipflop is end;
architecture test of tb_async_d_flipflop is
  signal d : std_logic := '0';
  signal clk : std_logic := '0';
  signal set : std_logic := '0';
  signal clr : std_logic := '0';
  signal q, qb : std_logic;
begin
  dut: entity work.async_d_flipflop port map (d => d, clk => clk, set => set, clr => clr, q => q, qb => qb);
  stimulus: process
  begin
    d <= '1';
    clk <= '0';
    set <= '0';
    clr <= '1';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Asynchronous clear" severity failure;
    report "PASS: Asynchronous clear";
    d <= '1';
    clk <= '0';
    set <= '1';
    clr <= '1';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Both asserted clear wins" severity failure;
    report "PASS: Both asserted clear wins";
    d <= '1';
    clk <= '0';
    set <= '1';
    clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Asynchronous set" severity failure;
    report "PASS: Asynchronous set";
    d <= '0';
    clk <= '0';
    set <= '0';
    clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Hold after release" severity failure;
    report "PASS: Hold after release";
    d <= '0';
    clk <= '1';
    set <= '0';
    clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Rising sample zero" severity failure;
    report "PASS: Rising sample zero";
    d <= '1';
    clk <= '1';
    set <= '0';
    clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: High clock data change" severity failure;
    report "PASS: High clock data change";
    d <= '1';
    clk <= '0';
    set <= '0';
    clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Falling hold" severity failure;
    report "PASS: Falling hold";
    d <= '1';
    clk <= '1';
    set <= '0';
    clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Rising sample one" severity failure;
    report "PASS: Rising sample one";
    d <= '1';
    clk <= '1';
    set <= '0';
    clr <= '1';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Clear with high clock" severity failure;
    report "PASS: Clear with high clock";
    d <= '0';
    clk <= '1';
    set <= '1';
    clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Set with high clock" severity failure;
    report "PASS: Set with high clock";
    report "ALL CASES PASS: async_d_flipflop";
    finish;
    wait;
  end process;
end;
