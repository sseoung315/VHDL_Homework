library ieee;
use ieee.std_logic_1164.all;
use std.env.all;
entity tb_jk_flipflop is end;
architecture test of tb_jk_flipflop is
  signal j : std_logic := '0';
  signal k : std_logic := '0';
  signal clk : std_logic := '0';
  signal init_clr : std_logic := '0';
  signal q, qb : std_logic;
begin
  dut: entity work.jk_flipflop port map (j => j, k => k, clk => clk, init_clr => init_clr, q => q, qb => qb);
  stimulus: process
  begin
    j <= '0';
    k <= '0';
    clk <= '0';
    init_clr <= '1';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Initialize" severity failure;
    report "PASS: Initialize";
    j <= '0';
    k <= '0';
    clk <= '0';
    init_clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Release clear" severity failure;
    report "PASS: Release clear";
    j <= '0';
    k <= '0';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Hold zero rising" severity failure;
    report "PASS: Hold zero rising";
    j <= '1';
    k <= '0';
    clk <= '0';
    init_clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Prepare set" severity failure;
    report "PASS: Prepare set";
    j <= '1';
    k <= '0';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Set rising" severity failure;
    report "PASS: Set rising";
    j <= '0';
    k <= '0';
    clk <= '0';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Prepare hold" severity failure;
    report "PASS: Prepare hold";
    j <= '0';
    k <= '0';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Hold one rising" severity failure;
    report "PASS: Hold one rising";
    j <= '0';
    k <= '1';
    clk <= '0';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Prepare reset" severity failure;
    report "PASS: Prepare reset";
    j <= '0';
    k <= '1';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Reset rising" severity failure;
    report "PASS: Reset rising";
    j <= '1';
    k <= '1';
    clk <= '0';
    init_clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Prepare toggle" severity failure;
    report "PASS: Prepare toggle";
    j <= '1';
    k <= '1';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Toggle rising one" severity failure;
    report "PASS: Toggle rising one";
    j <= '1';
    k <= '1';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: High clock hold" severity failure;
    report "PASS: High clock hold";
    j <= '1';
    k <= '1';
    clk <= '0';
    init_clr <= '0';
    wait for 20 ns;
    assert q='1' and qb='0' report "FAIL: Toggle falling hold" severity failure;
    report "PASS: Toggle falling hold";
    j <= '1';
    k <= '1';
    clk <= '1';
    init_clr <= '0';
    wait for 20 ns;
    assert q='0' and qb='1' report "FAIL: Toggle rising zero" severity failure;
    report "PASS: Toggle rising zero";
    report "ALL CASES PASS: jk_flipflop";
    finish;
    wait;
  end process;
end;
